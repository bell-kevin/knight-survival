// Width in pixels of the longest line of `text` at the given scale.
inline float textWidth(const std::string &text, int scale)
{
    size_t longest = 0, current = 0;
    for (char c : text)
    {
        current = (c == '\n') ? 0 : current + 1;
        longest = std::max(longest, current);
    }
    return longest == 0 ? 0 : (float)(longest * 6 - 1) * (float)scale;
}

// Draws `text` with its top-left corner at (x, y). Every font pixel becomes a scale x scale
// square. '\n' starts a new line.
inline void drawText(SDL_Renderer *renderer, const std::string &text, float x, float y, int scale, SDL_Color color)
{
    std::vector<SDL_FRect> pixels;
    float cx = x, cy = y, s = (float)scale;
    for (char ch : text)
    {
        if (ch == '\n')
        {
            cx = x;
            cy += 10 * s;
            continue;
        }
        int c = std::toupper((unsigned char)ch);
        if (c < 32 || c > 95)
            c = '?';
        const unsigned char *glyph = FONT[c - 32];
        for (int row = 0; row < 7; row++)
        {
            for (int col = 0; col < 5; col++)
            {
                if (glyph[row] & (0x10 >> col))
                    pixels.push_back({cx + col * s, cy + row * s, s, s});
            }
        }
        cx += 6 * s;
    }
    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    SDL_RenderFillRectsF(renderer, pixels.data(), (int)pixels.size());
}

// Same, with a dark copy one pixel down and right underneath, so it reads on any background.
inline void drawTextShadowed(SDL_Renderer *renderer, const std::string &text, float x, float y, int scale, SDL_Color color)
{
    float offset = (float)std::max(1, scale / 2);
    drawText(renderer, text, x + offset, y + offset, scale, {0, 0, 0, color.a});
    drawText(renderer, text, x, y, scale, color);
}
